"""Builds cdrom.js: the mounted CD's directory tree (the shell's fs.load tree format), read from its ISO 9660 image. A
file's entry carries the first sector of its extent, from which its bytes are read on the host's disc as the guest
opens it; the root's README.TXT and AUTORUN.INF carry their bytes.

    python3 tools/build_cdrom.py "Win95 OSR2.ISO" cdrom.js
"""
import base64, calendar, json, os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import provenance

iso, out = sys.argv[1], sys.argv[2]
f = open(iso, 'rb')
def sector(n, count=1): f.seek(n * 2048); return f.read(count * 2048)
pvd = sector(16); assert pvd[1:6] == b'CD001'
label = pvd[40:72].decode('ascii').strip()
# the Joliet descriptor (UCS-2 names) when the disc has one, as Windows 95 reads it, else the primary's names
desc, joliet = pvd, False
for n in range(17, 32):
    d = sector(n)
    if d[0] == 255: break
    if d[0] == 2 and d[88:91] in (b'%/@', b'%/C', b'%/E'): desc, joliet = d, True; break
def when(r):
    y, mo, dd, h, mi, s, tz = struct.unpack_from('<6Bb', r, 18)
    return (calendar.timegm((1900 + y, mo, dd, h, mi, s)) - tz * 15 * 60) * 1000
INLINE = {'README.TXT', 'AUTORUN.INF'}
def walk(lba, size, top):
    data, out, o = sector(lba, (size + 2047) // 2048), [], 0
    while o < size:
        n = data[o]
        if n == 0: o = (o // 2048 + 1) * 2048; continue
        r = data[o:o + n]; o += n
        ext, ln, flags, nl = struct.unpack_from('<I', r, 2)[0], struct.unpack_from('<I', r, 10)[0], r[25], r[32]
        raw = r[33:33 + nl]
        if raw in (b'\0', b'\1'): continue
        name = raw.decode('utf-16-be') if joliet else raw.decode('ascii')
        name = name.split(';')[0].rstrip('.')
        if flags & 2: out.append([name, when(r), walk(ext, ln, False)])
        elif top and name.upper() in INLINE: out.append([name, when(r), None, ln, base64.b64encode(sector(ext, (ln + 2047) // 2048)[:ln]).decode()])
        else: out.append([name, when(r), None, ln, None, ext])
    return sorted(out, key=lambda e: e[0].upper())
root = desc[156:190]
tree = walk(struct.unpack_from('<I', root, 2)[0], struct.unpack_from('<I', root, 10)[0], True)
with open(out, 'w') as fh:
    fh.write(provenance.line('tools/build_cdrom.py'))
    fh.write(f'// Directory tree of the mounted {label} CD. Generated by tools/build_cdrom.py from its image; a file is read from the\n'
             '// disc by its first sector, except the root README.TXT and AUTORUN.INF, whose bytes are here.\n')
    fh.write('window.W95CD = ' + json.dumps({'label': label, 'sectors': os.path.getsize(iso) // 2048, 'tree': tree}, separators=(',', ':')) + ';\n')
