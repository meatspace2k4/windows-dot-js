"""Builds assets-shell.js: toolbar and Taskbar Properties bitmaps, from the resources tools/extract.py writes.

    python3 tools/extract.py OUT comctl32.dll shell32.dll explorer.exe     (files from WIN95_02.CAB)
    cp marlett.ttf OUT/
    python3 tools/build_shell_assets.py OUT assets-shell.js
"""
import base64, io, json, sys
from PIL import Image, ImageDraw, ImageFont

src, out = sys.argv[1], sys.argv[2]
def png(name, transparent=None):
    im = Image.open(f'{src}/{name}').convert('RGBA')
    if transparent:   # toolbar strips use a key colour where the face shows through
        px = im.load()
        for y in range(im.height):
            for x in range(im.width):
                if px[x, y][:3] == transparent: px[x, y] = (0, 0, 0, 0)
    b = io.BytesIO(); im.save(b, 'PNG')
    return 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()

MAGENTA, SILVER = (255, 0, 255), (192, 192, 192)
img = {
    'tbstd': png('comctl32_bmp_120.png', SILVER),      # IDB_STD_SMALL_COLOR: cut copy paste undo redo delete new open save ...
    'tbview': png('comctl32_bmp_124.png', SILVER),     # IDB_VIEW_SMALL_COLOR: large small list details ... parent, map/disconnect drive
    'tpscene': png('explorer_bmp_149.png'),            # Taskbar Properties preview: the screen, small-icon Start menu
    'tpstartlarge': png('explorer_bmp_150.png'),       # the large-icon Start menu laid over it
    'tpbar': png('explorer_bmp_151.png'),              # the taskbar with its clock
    'tpnoclock': png('explorer_bmp_153.png'),          # the taskbar's right end without the clock
    'tpwindows': png('explorer_bmp_144.png'),           # windows, for a taskbar that is not on top
    'tpwindow': png('explorer_bmp_145.png'),
    'taskbar16': png('shell32_ico_40_16x16_4.png'),        # Settings > Taskbar...
    'taskbar32': png('shell32_ico_40_32x32_4.png'),
}
# Marlett's menu bullet, for the chosen item of a group (View > Large Icons ...); drawn as the shell draws its others
glyphs = {}
for name, ch, sz in [('bullet', 'h', 13)]:
    f = ImageFont.truetype(f'{src}/marlett.ttf', sz, encoding='symb')
    im = Image.new('L', (40, 40), 0); d = ImageDraw.Draw(im); d.fontmode = '1'; d.text((8, 8), chr(0xF000 + ord(ch)), font=f, fill=255)
    im = im.crop(im.getbbox())
    glyphs[name] = [im.width, im.height, [sum((1 << (im.width - 1 - x)) for x in range(im.width) if im.getpixel((x, y))) for y in range(im.height)]]
with open(out, 'w') as fh:
    fh.write('// Generated by tools/build_shell_assets.py from COMCTL32.DLL and EXPLORER.EXE (WIN95_02.CAB)\n')
    fh.write('Object.assign(window.W95.img, ' + json.dumps(img) + ');\n')
    fh.write('Object.assign(window.W95.glyphs, ' + json.dumps(glyphs) + ');\n')
