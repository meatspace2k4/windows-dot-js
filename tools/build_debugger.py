"""Build W95DBG.EXE, the Debugger (Programs > Accessories > System Tools), and write debugger-exe.js: its file, its
code recompiled as every program's is (recomp.py) and its metadata, as a program of the system's.

It is DBWIN.EXE's program with another library (build_dbwin.py's code): its entry calls W95DBG.DLL's Start, which
makes its window (debugger.js), then runs the message loop; its window procedure gives W95DBG.DLL's Handle every
message, DefWindowProcA what it does not answer.

    python3 tools/build_debugger.py
"""
import base64, json, os, subprocess, sys, tempfile
import build_claude as pe32
import build_dbwin

here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
BASE = 0x005A0000      # its load base: a program base of its own, past DBWIN.EXE's
LOOKUP = 0x07FF6000    # its block table, past DBWIN.EXE's
IMPORTS = [('W95DBG.DLL', ['Start', 'Handle']), ('USER32.dll', ['GetMessageA', 'TranslateMessage', 'DispatchMessageA', 'DefWindowProcA']),
           ('KERNEL32.dll', ['ExitProcess'])]

if __name__ == '__main__':
    build_dbwin.BASE = BASE   # (its code's absolute addresses: the window procedure's)
    pe32.BASE, pe32.IMPORTS, pe32.text = BASE, IMPORTS, build_dbwin.text
    os.environ['RECOMP_SHARED'] = '1'
    with tempfile.TemporaryDirectory() as tmp:
        exe = os.path.join(tmp, 'w95dbg.exe'); open(exe, 'wb').write(pe32.pe())
        out = os.path.join(tmp, 'w95dbg')
        subprocess.run([sys.executable, os.path.join(here, 'recomp.py'), exe, out, '--base', hex(BASE), '--lookup', hex(LOOKUP)], check=True)
        b64 = lambda p: base64.b64encode(open(p, 'rb').read()).decode()
        entry = {'file': b64(exe), 'wasm': b64(out + '.wasm'), 'meta': json.load(open(out + '.json'))}
    with open(os.path.join(root, 'debugger-exe.js'), 'w') as f:
        f.write('// Generated by tools/build_debugger.py: W95DBG.EXE, the Debugger, a program of the system\'s (system.js W95SYSTEM.programs)\n')
        f.write(f"window.W95SYSTEM.programs['W95DBG.EXE'] = {json.dumps(entry)};\n")
    print('debugger-exe.js:', len(entry['file']), 'bytes of image (base64),', len(entry['meta']['blocks']), 'blocks')
