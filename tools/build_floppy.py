"""Builds floppy.js: the A: floppy, a directory's files with their contents (the shell's fs.load tree format).

    python3 tools/build_floppy.py mac floppy.js
"""
import base64, json, os, sys

src, out = sys.argv[1], sys.argv[2]
SKIP = {'.DS_Store'}
def entry(p, name):
    t = int(os.stat(p).st_mtime * 1000)
    if os.path.isdir(p):
        return [name, t, [entry(os.path.join(p, k), k) for k in sorted(os.listdir(p)) if k not in SKIP and not k.endswith('.app')
                          and (os.path.isdir(os.path.join(p, k)) or p != src)]]
    b = open(p, 'rb').read()
    return [name, t, None, len(b), base64.b64encode(b).decode()]
# the directories under SRC, and the files inside them (SRC's own files are the app's build files, not the floppy's)
tree = [entry(os.path.join(src, k), k) for k in sorted(os.listdir(src)) if os.path.isdir(os.path.join(src, k)) and not k.endswith('.app')]
with open(out, 'w') as fh:
    fh.write(f'// Directory tree of the mounted A: floppy. Generated by tools/build_floppy.py from {os.path.basename(os.path.abspath(src))}/.\n')
    fh.write('window.W95FLOPPY = ' + json.dumps({'label': 'MAC', 'tree': tree}, separators=(',', ':')) + ';\n')
