"""TCP/IP's files from the Windows 95 CD image for the page (tcpip.js: window.W95SYSTEM.tcpip, which win95.js
setupNetwork puts in C:\\WINDOWS\\SYSTEM). The CD's cabinets are Quantum-compressed, which the page does not read: 7-Zip
reads them here. Usage: build_tcpip.py CDROM.ISO OUT.js"""
import base64, json, os, subprocess, sys, tempfile
iso, out = sys.argv[1], sys.argv[2]
FILES = ['afvxd.vxd', 'vtdi.386', 'vip.386', 'vtcp.386', 'vdhcp.386', 'vnbt.386', 'wsock.vxd', 'wshtcp.vxd', 'wsock32.dll', 'winsock.dll']
with tempfile.TemporaryDirectory() as t:
    subprocess.run(['7z', 'e', '-y', f'-o{t}', iso, 'WIN95/WIN95_*.CAB', 'WIN95/PRECOPY*.CAB'], check=True, stdout=subprocess.DEVNULL)
    subprocess.run(['7z', 'e', '-y', f'-o{t}/x', os.path.join(t, 'WIN95_02.CAB')] + FILES, check=True, stdout=subprocess.DEVNULL)
    got = {f.upper(): base64.b64encode(open(os.path.join(t, 'x', f), 'rb').read()).decode() for f in FILES}
with open(out, 'w') as o:
    o.write('// Generated by tools/build_tcpip.py from the Windows 95 CD: TCP/IP\'s files (win95.js setupNetwork)\n')
    o.write('window.W95SYSTEM = window.W95SYSTEM || {}; window.W95SYSTEM.tcpip = ' + json.dumps(got) + ';\n')
