"""The generated bundles in two parts, for a site served over a network: what the page needs to make its disk and
start MS-DOS (the system's files, fonts and setup files), and the recompiled code (each module's `wasm`), which only a
machine's worker runs and which is most of the bytes (140 of system.js's 168 MB). The page loads the first part and
shows the machine's screen; the code arrives behind it (host-web.js fetches it as the shell starts) and a worker
takes it as it starts (worker.js), putting each module's code back where it was.

    python3 tools/split_system.py --code site/system-code.js site/system.js site/savers.js

Each bundle given (a file of `window.NAME = {...};` after its comment lines) is rewritten in place without its `wasm`
strings; the code file is written with all of them, by bundle and by path; the first bundle is given `code`, the code
file's name beside it, which says the site is in two parts. Run by deploy/win95/deploy.sh on the staged copies: the
working tree's bundles stay whole, as the dev server, the app and the tests read them.
"""
import argparse, json, os, re

HEAD = re.compile(r'^((?:[ \t]*//[^\n]*\n|[ \t]*\n)*)[ \t]*window\.(\w+)[ \t]*=[ \t]*', re.S)
CODE = '''// Generated by tools/split_system.py: the recompiled code of %s, each module's put back where its bundle had it.
(function (code) {
  for (const name in code) {
    const root = self[name]; if (!root) continue;
    for (const [path, wasm] of code[name]) { let o = root; for (const k of path) o = o && o[k]; if (o) o.wasm = wasm; }
  }
})(%s);
'''


def read(path):
    """(the comment lines, the global's name, its value) of a bundle"""
    with open(path, encoding='utf-8') as f: s = f.read()
    m = HEAD.match(s)
    if not m: raise ValueError(f'{path}: not a bundle (window.NAME = {{...}};)')
    body = s[m.end():].rstrip()
    if body.endswith(';'): body = body[:-1]
    return m[1], m[2], json.loads(body)


def take(v, path, out):
    """the `wasm` strings under v, taken out of it into out as [path, wasm]"""
    if not isinstance(v, dict): return
    w = v.get('wasm')
    if isinstance(w, str) and w: out.append([path, w]); del v['wasm']
    for k, x in v.items():
        if isinstance(x, dict): take(x, path + [k], out)


def write(path, text):
    tmp = path + '.split'
    with open(tmp, 'w', encoding='utf-8') as f: f.write(text)
    os.replace(tmp, path)


def split(bundles, code_path):
    """the bundles rewritten without their code, the code file written; (bytes of data, bytes of code)"""
    code, data, names = {}, 0, []
    for i, path in enumerate(bundles):
        head, name, value = read(path)
        if name in code: raise ValueError(f'{path}: {name} given twice')
        if isinstance(value, dict) and 'code' in value and i == 0: raise ValueError(f'{path}: already in two parts')
        out = []; take(value, [], out)
        if not out: raise ValueError(f'{path}: no code in it')
        code[name] = out; names.append(name)
        if i == 0: value['code'] = os.path.basename(code_path)
        text = f'{head}window.{name} = {json.dumps(value, separators=(",", ":"))};\n'
        write(path, text); data += len(text)
    text = CODE % (', '.join(names), json.dumps(code, separators=(',', ':')))
    write(code_path, text)
    return data, len(text)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--code', required=True, help='the code file to write, beside the bundles')
    ap.add_argument('bundles', nargs='+'); a = ap.parse_args()
    d, c = split(a.bundles, a.code)
    print(f'split_system: {d >> 20} MB for the page, {c >> 20} MB of code in {os.path.basename(a.code)}')
