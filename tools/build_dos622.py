"""Write dos622.js: MS-DOS 6.22 as SYS.COM puts it on a hard disk, taken from its Setup Disk 1 (a 1.44 MB image, FAT12,
bootable): the boot sector SYS writes (Disk 1's own: the same code for FAT12 and FAT16, its BPB filled in for the
volume), IO.SYS and MSDOS.SYS (the first two entries of the root, as the boot sector looks for them) and COMMAND.COM.

    python3 tools/build_dos622.py OUT.js DISK1.IMG
"""
import base64, json, sys

out, src = sys.argv[1], sys.argv[2]
img = open(src, 'rb').read()
u16 = lambda o: int.from_bytes(img[o:o + 2], 'little')
bps, spc, res, nfat, nroot, fatsz = u16(11), img[13], u16(14), img[16], u16(17), u16(22)
root0 = (res + nfat * fatsz) * bps; data0 = root0 + nroot * 32
fat = img[res * bps:(res + fatsz) * bps]
def next12(c):
    v = int.from_bytes(fat[c * 3 // 2:c * 3 // 2 + 2], 'little')
    return v >> 4 if c & 1 else v & 0xfff
def read(cl, size):
    b = bytearray()
    while 2 <= cl < 0xff8 and len(b) < size:
        o = data0 + (cl - 2) * spc * bps; b += img[o:o + spc * bps]; cl = next12(cl)
    return bytes(b[:size])
files = {}
for i in range(nroot):
    e = img[root0 + i * 32:root0 + i * 32 + 32]
    if e[0] in (0, 0xe5) or e[11] & 0x18: continue
    name = e[:8].decode('latin1').rstrip() + ('.' + e[8:11].decode('latin1').rstrip() if e[8:11].strip() else '')
    if name in ('IO.SYS', 'MSDOS.SYS', 'COMMAND.COM'): files[name] = read(u16(i * 32 + root0 + 26), int.from_bytes(e[28:32], 'little'))
assert set(files) == {'IO.SYS', 'MSDOS.SYS', 'COMMAND.COM'}, sorted(files)
bundle = {'boot': base64.b64encode(img[:512]).decode(), 'files': {n: base64.b64encode(d).decode() for n, d in files.items()}}
with open(out, 'w') as f:
    f.write('// Generated by tools/build_dos622.py from MS-DOS 6.22\'s Setup Disk 1: MS-DOS as SYS.COM puts it on a hard disk\n')
    f.write(f'window.W95DOS622 = {json.dumps(bundle)};\n')
print(out, {n: len(d) for n, d in files.items()})
